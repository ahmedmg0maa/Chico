/* Deterministic CHICO executive CSS bundle.
 * Entrypoint: /v2 imports only executive-unified.css.
 * The legacy files remain edit-only modules during migration; they are never
 * independently loaded by the browser. Exact-context declarations overridden
 * by a later equally/more important declaration are pruned safely.
 */
const fs=require('node:fs'),path=require('node:path'),postcss=require('postcss');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'src/components/v2');
const order=['executive.css','executive-v7.css','executive-v8.css','executive-v9.css','executive-v10.css','executive-v11.css','executive-v12.css'];
const combined=postcss.root();
for(const file of order){
 const source=fs.readFileSync(path.join(dir,file),'utf8');
 const tree=postcss.parse(source,{from:file});
 combined.append(postcss.comment({text:'CHICO source: '+file}));
 for(const node of tree.nodes||[])combined.append(node.clone());
}
const seen=new Map();
let removedDeclarations=0,removedRules=0;
const all=[];
combined.walkRules(rule=>all.push(rule));
for(let i=all.length-1;i>=0;i--){
 const rule=all[i];
 const scope=[];let parent=rule.parent,skip=false;
 while(parent&&parent.type!=='root'){
  if(parent.type==='atrule'){
   const type=String(parent.name||'').toLowerCase();
   if(type.includes('keyframes'))skip=true;
   scope.unshift('@'+type+' '+String(parent.params||'').trim());
  }else if(parent.type==='rule')scope.unshift('RULE:'+parent.selector);
  parent=parent.parent;
 }
 if(skip)continue;
 const selector=String(rule.selector||'').trim();
 for(let j=(rule.nodes||[]).length-1;j>=0;j--){
  const decl=rule.nodes[j];if(decl.type!=='decl')continue;
  const key=scope.join(' > ')+' | '+selector+' | '+decl.prop.toLowerCase();
  const priority=decl.important?1:0;
  if(seen.has(key)&&seen.get(key)>=priority){decl.remove();removedDeclarations++;continue;}
  seen.set(key,priority);
 }
 if(!rule.nodes||rule.nodes.length===0){rule.remove();removedRules++;}
}
const header='/* CHICO executive UI · generated by scripts/build-executive-css.cjs\n * Preserve the module order. Do not edit this generated file by hand.\n */\n';
const output=header+combined.toString().trim()+'\n';
const target=path.join(dir,'executive-unified.css');
fs.writeFileSync(target,output);
console.log('CHICO CSS: '+order.length+' modules, '+removedDeclarations+' obsolete declarations, '+removedRules+' empty rules; '+output.length+' bytes');
