-- CHICO Command Center · native Supabase PostgreSQL, server-owned schema.
-- Run this script in Supabase SQL Editor if automatic bootstrap isn't permitted.
-- All tables live in schema chico, not exposed via Supabase public Data API.
CREATE SCHEMA IF NOT EXISTS chico;
CREATE TABLE IF NOT EXISTS chico.settings(key text PRIMARY KEY, value text NOT NULL);
CREATE TABLE IF NOT EXISTS chico.members(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE,
 rank text NOT NULL, active integer NOT NULL DEFAULT 1, joined_on text, resigned_on text,
 display_order integer NOT NULL DEFAULT 10000, in_reporting integer NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX IF NOT EXISTS chico_member_name_ci ON chico.members(lower(name));
CREATE TABLE IF NOT EXISTS chico.ranks(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id bigint NOT NULL REFERENCES chico.members(id), rank text NOT NULL, effective_on text NOT NULL, grace integer NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS chico.weeks(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, starts text NOT NULL UNIQUE,
 ends text NOT NULL, status text NOT NULL DEFAULT 'open', opened_at text,
 closed_at text, closing_note text, closing_snapshot text
);
CREATE TABLE IF NOT EXISTS chico.openings(
 week_id bigint NOT NULL REFERENCES chico.weeks(id), member_id bigint NOT NULL REFERENCES chico.members(id),
 flags_base integer NOT NULL, updated_at text NOT NULL, PRIMARY KEY(week_id,member_id)
);
CREATE TABLE IF NOT EXISTS chico.entries(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 week_id bigint NOT NULL REFERENCES chico.weeks(id), member_id bigint NOT NULL REFERENCES chico.members(id),
 start_on text NOT NULL, end_on text NOT NULL, mode text NOT NULL,
 tickets integer NOT NULL, tickets_counter integer, previous_tickets integer,
 flags_counter integer, previous_flags integer, flags integer,
 rate double precision, hours double precision, note text NOT NULL DEFAULT '',
 revision text NOT NULL, updated_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS chico_entries_person ON chico.entries(member_id,end_on);
CREATE TABLE IF NOT EXISTS chico.snapshots(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind text NOT NULL,
 week_id bigint NOT NULL, created_at text NOT NULL, payload text NOT NULL
);
CREATE TABLE IF NOT EXISTS chico.audit(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at text NOT NULL, action text NOT NULL, detail text NOT NULL
);
CREATE TABLE IF NOT EXISTS chico.sessions(
 token_hash text PRIMARY KEY, expires text NOT NULL, role text NOT NULL DEFAULT 'team', username text
);
CREATE TABLE IF NOT EXISTS chico.users(
 username text PRIMARY KEY, password_hash text NOT NULL, role text NOT NULL,
 active integer NOT NULL DEFAULT 1, created_at text NOT NULL
);
CREATE TABLE IF NOT EXISTS chico.rate_evaluations(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 week_id bigint NOT NULL REFERENCES chico.weeks(id), member_id bigint NOT NULL REFERENCES chico.members(id),
 evaluation_date text NOT NULL, rate double precision NOT NULL, revision text NOT NULL,
 entered_at text NOT NULL, updated_at text NOT NULL, UNIQUE(member_id,evaluation_date)
);
CREATE TABLE IF NOT EXISTS chico.shift_assignments(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, member_id bigint NOT NULL REFERENCES chico.members(id),
 shift text NOT NULL, effective_on text NOT NULL, created_at text NOT NULL
);
CREATE TABLE IF NOT EXISTS chico.data_migrations(name text PRIMARY KEY, applied_at text NOT NULL);
CREATE TABLE IF NOT EXISTS chico.excel_imports(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, source_hash text NOT NULL,
 for_date text NOT NULL, rows_count integer NOT NULL, saved_at text NOT NULL,
 operator text NOT NULL, summary text NOT NULL
);
CREATE TABLE IF NOT EXISTS chico.import_previews(
 ticket_hash text PRIMARY KEY, session_hash text NOT NULL, parsed text NOT NULL,
 source_hash text NOT NULL, expires_at text NOT NULL
);
CREATE TABLE IF NOT EXISTS chico.backups(
 filename text PRIMARY KEY, kind text NOT NULL, created_at text NOT NULL,
 content text NOT NULL, sha256 text NOT NULL
);
CREATE TABLE IF NOT EXISTS chico.login_attempts(
 source_hash text NOT NULL, at text NOT NULL
);
CREATE INDEX IF NOT EXISTS chico_login_idx ON chico.login_attempts(source_hash,at);
-- Deny direct client access. API connects via a server secret and checks owner/team permissions.
REVOKE ALL ON SCHEMA chico FROM anon, authenticated, PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA chico FROM anon, authenticated, PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA chico FROM anon, authenticated, PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA chico REVOKE ALL ON TABLES FROM anon, authenticated, PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA chico REVOKE ALL ON SEQUENCES FROM anon, authenticated, PUBLIC;
